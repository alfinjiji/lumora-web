import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
const spec = JSON.parse(
  readFileSync("apps/api/resources/contract.json", "utf8"),
);
const routes = JSON.parse(readFileSync(".local/routes.json", "utf8"));
const rows = [];
for (const [path, methods] of Object.entries(spec.paths))
  for (const [method, op] of Object.entries(methods)) {
    if (!op.operationId) continue;
    const route = routes.find(
      (r) =>
        "/" + r.uri === path &&
        r.method.split("|").includes(method.toUpperCase()),
    );
    if (!route) throw new Error("Missing route " + method + " " + path);
    const capability = op["x-capability"];
    const boundary = ["owner", "staff"].includes(capability)
      ? "IdentityTest: anonymous/customer denial"
      : ["authenticated", "customer", "verified-customer"].includes(capability)
        ? "ContractBoundaryTest: anonymous denial"
        : capability === "provider"
          ? "ContractBoundaryTest: signature, duplicate/replaced event"
          : "ResourcesTest / CommerceTest / RecoveryAccessTest (representative scenarios)";
    const handler = route.action
      .replace("App\\Modules\\", "")
      .replaceAll("\\", "/");
    rows.push(
      `| ${method.toUpperCase()} \`${path}\` | ${capability} | \`${handler}\` | ${boundary} |`,
    );
  }
const header = `# Frozen API coverage\n\n${rows.length} qualified operations map to explicit runtime routes. The matrix is generated by scripts/coverage.mjs from the contract and Laravel route:list output. Controller modules identify the implementation and the corresponding storefront/admin feature.\n\nBoundary tests exercise every owner/staff and account-only operation before validation. Scenario tests exercise real catalogue/media/content, guest/account access, shipping, stock, settlement, refunds and fulfillment; Playwright exercises critical visible journeys. A route and a permission assertion do not imply an independent positive integration test for every possible operation/payload. Real provider/hosting validation remains separate.\n\n| Operation | Capability | Controller / consumer module | Automated boundary evidence |\n|---|---|---|---|\n`;
writeFileSync(
  "docs/implementation/API-COVERAGE.md",
  header + rows.join("\n") + "\n",
);
writeFileSync(
  "contracts/openapi.sha256",
  createHash("sha256")
    .update(readFileSync("contracts/openapi.yaml"))
    .digest("hex") + "  contracts/openapi.yaml\n",
);
console.log(`Mapped ${rows.length} routes and recorded contract freeze hash.`);
