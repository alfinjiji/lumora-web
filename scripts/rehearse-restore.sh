#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
backup_dir=${1:?Provide a private backup directory}
(cd "$backup_dir" && sha256sum --check SHA256SUMS >/dev/null)
# Fixed disposable schema, never the configured application database.
scripts/docker.sh compose exec -T mysql sh -c 'MYSQL_PWD="$MYSQL_ROOT_PASSWORD" mysql -uroot -e "CREATE DATABASE IF NOT EXISTS auraflare_restore_rehearsal;"'
gunzip -c "$backup_dir/database.sql.gz" | scripts/docker.sh compose exec -T mysql sh -c 'MYSQL_PWD="$MYSQL_ROOT_PASSWORD" mysql -uroot auraflare_restore_rehearsal'
scripts/docker.sh compose exec -T mysql sh -c 'MYSQL_PWD="$MYSQL_ROOT_PASSWORD" mysql -uroot --batch --skip-column-names auraflare_restore_rehearsal -e "SELECT CONCAT('\''Restored order count: '\'',COUNT(*)) FROM orders; SELECT CONCAT('\''Restored movement count: '\'',COUNT(*)) FROM inventory_movements;"'
mkdir -p .local/restore-media
# The archive is generated by backup.sh from our own storage; never use arbitrary uploads here.
tar -xzf "$backup_dir/local-media.tar.gz" -C .local/restore-media
printf '%s\n' 'Restore rehearsal completed in the disposable schema and .local/restore-media. Application database and media were not replaced.'
